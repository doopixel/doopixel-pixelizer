(function () {
  const PLATE_WIDTH = 16;
  const SCALING_FACTOR = 40;
  const LOW_DPI = 48;
  const HIGH_DPI = 96;

  function setDPI(canvas, dpi) {
    canvas.style.width = canvas.width + "px";
    canvas.style.height = canvas.height + "px";

    const scaleFactor = dpi / 96;
    const backup = canvas.cloneNode(false);
    backup.getContext("2d").drawImage(canvas, 0, 0);
    const width = canvas.width;
    const height = canvas.height;
    canvas.width = Math.ceil(width * scaleFactor);
    canvas.height = Math.ceil(height * scaleFactor);
    canvas.getContext("2d").drawImage(backup, 0, 0, canvas.width, canvas.height);
  }

  function addWatermark(pdf, highQuality) {
    for (let page = 1; page <= pdf.internal.getNumberOfPages(); page += 1) {
      pdf.setPage(page);
      pdf.setFontSize(highQuality ? 20 : 10);
      pdf.setTextColor(205);
      pdf.text(pdf.internal.pageSize.height * 0.25, pdf.internal.pageSize.height * 0.3, "Generated by DooPixel");
    }
  }

  function safeFilename(value) {
    return String(value || "Pixel-Art")
      .replace(/[^a-z0-9-_ ]/gi, "")
      .trim()
      .replace(/\s+/g, "-")
      .slice(0, 60) || "Pixel-Art";
  }

  async function generate(instructionData, options) {
    const decoded = await window.DooPixelInstructionData.decode(instructionData);
    const highQuality = Boolean(options && options.highQuality);
    const onProgress = (options && options.onProgress) || function () {};
    const title = (options && options.title) || "Pixel Art";

    decoded.palette.forEach(function (color) {
      const warehouseCode = window.DooPixelInstructionData.formatWarehouseCode(
        decoded.pieceType,
        color.doopixelNo
      );
      HEX_TO_COLOR_NAME[color.hex] = warehouseCode + " - " + color.colorName;
    });

    const finalImageCanvas = document.createElement("canvas");
    drawStudImageOnCanvas(
      decoded.pixelArray,
      decoded.width,
      SCALING_FACTOR,
      finalImageCanvas,
      decoded.pieceType,
      null
    );

    const paletteOrder = decoded.palette.map(function (color) { return color.hex; });
    const titleCanvas = document.createElement("canvas");
    generateInstructionTitlePage(
      decoded.pixelArray,
      decoded.width,
      PLATE_WIDTH,
      paletteOrder,
      SCALING_FACTOR,
      finalImageCanvas,
      titleCanvas,
      decoded.pieceType
    );
    setDPI(titleCanvas, highQuality ? HIGH_DPI : LOW_DPI);

    let pdf = new jsPDF({
      orientation: titleCanvas.width < titleCanvas.height ? "p" : "l",
      unit: "mm",
      format: [titleCanvas.width, titleCanvas.height],
    });
    const pdfWidth = pdf.internal.pageSize.getWidth();
    const pdfHeight = pdf.internal.pageSize.getHeight();
    pdf.addImage(
      titleCanvas.toDataURL("image/png", 1),
      "PNG",
      0,
      0,
      pdfWidth,
      (pdfWidth * titleCanvas.height) / titleCanvas.width
    );

    const totalPlates = (decoded.width / PLATE_WIDTH) * (decoded.height / PLATE_WIDTH);
    const splitEvery = highQuality ? 20 : 50;
    let partNumber = 1;
    onProgress(0, totalPlates);

    for (let plateIndex = 0; plateIndex < totalPlates; plateIndex += 1) {
      if (plateIndex > 0 && plateIndex % splitEvery === 0) {
        addWatermark(pdf, highQuality);
        pdf.save(`DooPixel-${safeFilename(title)}-Instructions-Part-${partNumber}.pdf`);
        partNumber += 1;
        pdf = new jsPDF({
          orientation: titleCanvas.width < titleCanvas.height ? "p" : "l",
          unit: "mm",
          format: [titleCanvas.width, titleCanvas.height],
        });
      } else {
        pdf.addPage();
      }

      const pageCanvas = document.createElement("canvas");
      generateInstructionPage(
        getSubPixelArray(decoded.pixelArray, plateIndex, decoded.width, PLATE_WIDTH),
        PLATE_WIDTH,
        paletteOrder,
        SCALING_FACTOR,
        pageCanvas,
        plateIndex + 1,
        decoded.pieceType,
        null
      );
      setDPI(pageCanvas, highQuality ? HIGH_DPI : LOW_DPI);
      pdf.addImage(
        pageCanvas.toDataURL("image/png", 1),
        "PNG",
        0,
        0,
        pdfWidth,
        (pdfWidth * pageCanvas.height) / pageCanvas.width
      );
      onProgress(plateIndex + 1, totalPlates);
      await new Promise(function (resolve) { window.setTimeout(resolve, 0); });
    }

    addWatermark(pdf, highQuality);
    pdf.save(
      partNumber > 1
        ? `DooPixel-${safeFilename(title)}-Instructions-Part-${partNumber}.pdf`
        : `DooPixel-${safeFilename(title)}-Instructions.pdf`
    );
  }

  window.DooPixelProjectInstructions = { generate: generate };
})();
